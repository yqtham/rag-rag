// Helper to generate realistic candles
function generateCandles(basePrice: number, volatility: number = 0.015, count: number = 40): Candle[] {
  const candles: Candle[] = [];
  let currentClose = basePrice * (1 - volatility * (count / 2) * 0.1);
  const now = Date.now();
  const stepMs = 3600 * 1000 * 4; // 4-hour candles

  for (let i = 0; i < count; i++) {
    const timeStr = new Date(now - (count - i) * stepMs).toLocaleDateString('en-US', {
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
    const delta = (Math.random() - 0.48) * volatility * currentClose;
    const open = Number((currentClose).toFixed(2));
    const close = Number((currentClose + delta).toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * volatility * 0.6 * currentClose).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * volatility * 0.6 * currentClose).toFixed(2));
    const volume = Math.floor(basePrice > 1000 ? Math.random() * 5000 + 1000 : Math.random() * 800000 + 150000);

    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
    });
    currentClose = close;
  }
  return candles;
}

function extractSparkline(candles: Candle[]): number[] {
  return candles.map(c => c.close);
}

